/* m[i] bit j: operator j modulates operator i. FM6_ALG runs the sixth operator first; who wrote a bus modulates its reader */
static void fm_routes(uint32_t alg, uint8_t *m)
{
    const uint8_t *f = FM6_ALG[alg & 31u];
    uint8_t bus[4] = {0, 0, 0, 0};
    uint32_t k;
    for (k = 0; k < 6u; k++) {
        uint32_t op = 5u - k, in = (f[k] >> 4) & 3u, out = f[k] & 3u;
        m[op] = in ? bus[in] : 0u;
        bus[out] = (uint8_t)(((f[k] & FM6_OADD) ? bus[out] : 0u) | 1u << op);
    }
}

static int fm_is_carrier(uint32_t alg, uint32_t op) { return (FM6_ALG[alg & 31u][5u - op] & 3u) == 0u; }

/* the operator with feedback */
static uint32_t fm_feedback_op(uint32_t alg)
{
    uint32_t k;
    for (k = 0; k < 5u && (FM6_ALG[alg & 31u][5u - k] & 0xC0u) != 0xC0u; k++)
        ;
    return k;
}
