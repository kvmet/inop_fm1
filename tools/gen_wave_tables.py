"""The WAVE engine's wavetables, generated here from math: nothing is sampled from another instrument.

Each frame is one cycle, band-limited to several sizes. A note reads the largest size whose top harmonic stays
under Nyquist. Sizes keep 4 samples per cycle of the top harmonic, since the engine reads with linear interpolation.
  gen_wave_tables.py OUT.h"""
import cmath
import math
import random
import sys
from pathlib import Path

TABLES = ["HARM", "PWM", "SYNC", "VOX", "FOLD", "DIGI", "METAL", "GRIT"]
FRAMES = 16
TOP_BITS = 9                     # the largest size: 512 samples, 128 harmonics
SIZES = 7                        # down to 8 samples, 2 harmonics
FFT_N = 4096
TARGET_RMS = 0.35                # of full scale; a frame with too high a peak for this stays at its peak limit
PEAK = 0.95


def fft(x, inverse=False):
    n = len(x)
    if n == 1:
        return list(x)
    even, odd = fft(x[0::2], inverse), fft(x[1::2], inverse)
    sign = 2j if inverse else -2j
    out = [0j] * n
    for k in range(n // 2):
        t = cmath.exp(sign * math.pi * k / n) * odd[k]
        out[k], out[k + n // 2] = even[k] + t, even[k] - t
    return out


def from_partials(partials):
    """partials: {harmonic: amplitude}, summed in sine phase so that a morph between frames stays smooth"""
    spec = [0j] * FFT_N
    for k, a in partials.items():
        if 0 < k < FFT_N // 2:
            spec[k] = -0.5j * a
            spec[FFT_N - k] = 0.5j * a
    return [v.real for v in fft(spec, True)]


def harm(u):
    top = 1 + u * 31
    return from_partials({k: min(1.0, top - k + 1) / k ** 0.6 for k in range(1, int(top) + 2)})


def pwm(u):
    w = 0.5 - u * 0.47
    return [(1.0 if i / FFT_N < w else 0.0) - w for i in range(FFT_N)]


def sync(u):
    ratio = 1 + u * 7
    return [2 * (i / FFT_N * ratio % 1.0) - 1 for i in range(FFT_N)]


VOWELS = [(730, 1090, 2440), (530, 1840, 2480), (270, 2290, 3010), (570, 840, 2410), (300, 870, 2240)]   # a e i o u, Hz


def vox(u):
    at = u * (len(VOWELS) - 1)
    i = min(int(at), len(VOWELS) - 2)
    formants = [a + (b - a) * (at - i) for a, b in zip(VOWELS[i], VOWELS[i + 1])]
    partials = {}
    for k in range(1, 129):
        hz = k * 110.0
        partials[k] = sum(g * math.exp(-((hz - f) / 110.0) ** 2) for f, g in zip(formants, (1.0, 0.6, 0.3))) + 0.02 / k
    return from_partials(partials)


def fold(u):
    gain = 0.5 + u * 7.5
    return [math.sin(math.pi * gain * math.sin(2 * math.pi * i / FFT_N)) for i in range(FFT_N)]


def digi(u):
    frame = round(u * (FRAMES - 1))
    r = random.Random(0x1D160 + frame // 2)           # pairs of frames share partials, so the table moves in jumps
    count = 4 + frame * 2
    partials = {r.randrange(1, 8 + frame * 6): r.random() ** 2 + 0.1 for _ in range(count)}
    partials[1] = 1.0
    return from_partials(partials)


BAR_MODES = (1.0, 2.76, 5.4, 8.93, 13.34, 18.64)


def metal(u):
    base = 2 + u * 6
    partials = {}
    for m, ratio in enumerate(BAR_MODES):
        centre = base * ratio
        for k in range(max(1, int(centre) - 1), int(centre) + 3):
            partials[k] = partials.get(k, 0.0) + math.exp(-abs(k - centre) * 1.5) / (1 + m * 0.4)
    return from_partials(partials)


def grit(u):
    gain = 1 + u * 7
    levels = 2 ** (7 - u * 6)
    out = []
    for i in range(FFT_N):
        x = i / FFT_N
        v = max(-1.0, min(1.0, gain * (0.7 * math.sin(2 * math.pi * x) + 0.3 * (2 * x - 1))))
        out.append(round(v * levels) / levels)
    return out


SHAPES = [harm, pwm, sync, vox, fold, digi, metal, grit]


def band_limited(spec, bits):
    """one cycle of 2^bits samples with 2^(bits - 2) harmonics"""
    n = 1 << bits
    top = n >> 2
    small = [0j] * n
    for k in range(1, top + 1):
        small[k] = spec[k]
        small[n - k] = spec[FFT_N - k]
    return [v.real / FFT_N for v in fft(small, True)]


def frame_sizes(shape, u):
    spec = fft([complex(v) for v in shape(u)])
    spec[0] = 0j
    sizes = [band_limited(spec, TOP_BITS - m) for m in range(SIZES)]
    rms = math.sqrt(sum(v * v for v in sizes[0]) / len(sizes[0])) or 1.0
    peak = max(abs(v) for s in sizes for v in s) or 1.0
    gain = min(TARGET_RMS / rms, PEAK / peak) * 32767
    return [[int(round(v * gain)) for v in s] for s in sizes]


def main():
    out = [f"/* generated by tools/gen_wave_tables.py */\n#define WAVE_TABLES {len(TABLES)}u\n#define WAVE_FRAMES {FRAMES}u\n",
           f"#define WAVE_TOP_BITS {TOP_BITS}u\n#define WAVE_SIZES {SIZES}u\n"]
    total = sum(1 << (TOP_BITS - m) for m in range(SIZES))
    out.append(f"static const int16_t WAVE_DATA[WAVE_TABLES][WAVE_FRAMES][{total}] = {{\n")
    for name, shape in zip(TABLES, SHAPES):
        out.append(f"  {{ /* {name} */\n")
        for f in range(FRAMES):
            samples = [v for s in frame_sizes(shape, f / (FRAMES - 1)) for v in s]
            out.append("    {" + ",".join(map(str, samples)) + "},\n")
        out.append("  },\n")
    out.append("};\n")
    Path(sys.argv[1]).write_text("".join(out))
    print(f"  ok    wave tables {len(TABLES) * FRAMES * total * 2} B")


if __name__ == "__main__":
    main()
